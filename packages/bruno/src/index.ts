import nodeFs from "node:fs";
import path from "node:path";
import type { PluginFunction, Types } from "@graphql-codegen/plugin-helpers";
import type { GraphQLSchema, OperationTypeNode } from "graphql";
import { asBruno, type BrunoPluginConfig } from "./bruno";
import { extractOperations } from "./operations";

export const plugin: PluginFunction<BrunoPluginConfig> = async (
	schema: GraphQLSchema,
	documents: Types.DocumentFile[],
	config,
	info,
): Promise<string> => {
	if (!info?.outputFile) {
		throw new Error("Output directory not provided");
	}
	const outputDir = path.dirname(info.outputFile);
	if (config.clean) {
		cleanGeneratedFiles(outputDir);
	}

	const operations = extractOperations(schema, documents).sort((a, b) =>
		a.name.localeCompare(b.name),
	);
	const result: Record<string, Record<string, string>> = {};
	for (const operation of operations) {
		const fileName = `${operation.name}.bru`;
		const outputPath = path.join(
			outputDir,
			OPERATION_FOLDERS[operation.kind],
			fileName,
		);

		outputFileSync(outputPath, asBruno(operation, config));
		result[operation.name] = {
			filename: fileName,
			source: operation.location
				? path.relative(outputDir, operation.location)
				: "(unknown)",
		};
	}
	return JSON.stringify(result, null, 2);
};

/** The folder (in the output directory) per operation type. */
const OPERATION_FOLDERS: Record<OperationTypeNode, string> = {
	query: "queries",
	mutation: "mutations",
	subscription: "subscriptions",
};

/**
 * Removes the requests generated by a previous run: the `.bru` files in the
 * folders this plugin writes to, and those folders when they are empty
 * afterwards. Other files, such as `bruno.json`, environments or a
 * `folder.bru` with folder settings, are kept.
 */
function cleanGeneratedFiles(outputDir: string): void {
	for (const folder of Object.values(OPERATION_FOLDERS)) {
		const dirPath = path.join(outputDir, folder);
		if (!nodeFs.existsSync(dirPath)) {
			continue;
		}
		for (const entry of nodeFs.readdirSync(dirPath, { withFileTypes: true })) {
			if (
				entry.isFile() &&
				entry.name.endsWith(".bru") &&
				entry.name !== "folder.bru"
			) {
				nodeFs.rmSync(path.join(dirPath, entry.name));
			}
		}
		if (nodeFs.readdirSync(dirPath).length === 0) {
			nodeFs.rmdirSync(dirPath);
		}
	}
}

function outputFileSync(filePath: string, content: string): void {
	const dirPath = path.dirname(filePath);
	if (!nodeFs.existsSync(dirPath)) {
		nodeFs.mkdirSync(dirPath, { recursive: true });
	}
	nodeFs.writeFileSync(filePath, content);
}

export type { BrunoPluginConfig };
